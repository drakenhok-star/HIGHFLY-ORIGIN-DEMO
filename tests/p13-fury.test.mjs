// P13 FURY Movement Engine: real surface math + parkour FSM + regression contracts.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=async path=>readFile(new URL('../'+path,import.meta.url),'utf8');
const asModule=t=>'data:text/javascript;base64,'+Buffer.from(t).toString('base64');
const surfSrc=await source('src/player/fury-surfaces-p13.js');
const surfaces=await import(asModule(surfSrc));
const travelSrc=(await source('src/player/fury-traversal-p13.js'))
  .replace("'./fury-surfaces-p13.js'",JSON.stringify(asModule(surfSrc)));
const travel=await import(asModule(travelSrc));
const rock={x:0,z:0,r:1,minY:-.5,maxY:2.2,kind:'rock'};
const tree={...rock,kind:'tree'};
const almost=(a,b,msg)=>assert.ok(Math.abs(a-b)<1e-5,msg||a+' ~= '+b);
let c=surfaces.circularContact(rock,1.5,1,0);
assert.equal(c.kind,'rock');almost(c.nx,1);almost(c.nz,0);
assert.equal(surfaces.circularContact(tree,1.5,1,0),null,'tree collides but no climb yet');
assert.equal(surfaces.circularContact(rock,4,1,0),null,'distant rock is not climbable');
assert.equal(surfaces.circularContact(rock,1.5,8,0),null,'do not grab a rock many meters below');
const wall={x:5,z:1,ry:0,hw:2.75,hd:2.25};
c=surfaces.boxContact(wall,8.22,1,1,0);assert.equal(c.kind,'building');
assert.ok(c.nx>.99&&Math.abs(c.nz)<.01,'wall normal outward');
assert.equal(surfaces.boxContact(wall,16,1,1,0),null);
const tangent=surfaces.wallTangent(1,0,-1,0,1);
almost(Math.hypot(tangent.x,tangent.z),1);almost(tangent.x,0);
assert.equal(surfaces.canGrabLedge(surfaces.circularContact(rock,1.5,1.15,0),1.15,-2,true),true);
assert.equal(surfaces.canGrabLedge(surfaces.circularContact(rock,1.5,1.15,0),1.15,2,true),false);
assert.equal(surfaces.canGrabLedge(surfaces.circularContact(rock,1.5,1.15,0),1.15,-2,false),false);
const obs={query:()=>[rock,tree]};
const map={scatter:{obstacles:obs},interiors:{inside:false},
 structures:{colliders:[]},terrain:{getHeight:()=>0}};
assert.equal(surfaces.closestTraversalSurface(map,{x:1.5,y:1.3,z:0}).kind,'rock');
assert.equal(surfaces.landingRock(map,.5,0,2.35,2.1).top,2.2,'landing from above');
assert.equal(surfaces.landingRock(map,.5,0,1.1,1.0),null,'cannot stand on rock while underneath');
const player={pos:{x:1.5,y:1.1,z:0},vel:{x:0,y:-2,z:0},
 onGround:false,dashT:-1,_jumpCount:1,_jumpBufferT:0,bodyYaw:0,
 rig:{root:{rotation:{x:0,y:0,z:0},position:{y:0}}}};
const stats={sp:110,useStamina(n){if(this.sp<n)return false;this.sp-=n;return true;}};
const game={...map,stats,player};
const p=new travel.FuryTraversalP13(game,player);
p.update(.016,true,-1,0);
assert.equal(p.mode,'HANG','descending toward a climbable rock captures the ledge');
assert.ok(player.vel.y===0,'ledge hold cancels gravity');
assert.equal(p.jumpFromWall(),true,'jump while hanging climbs rock ledge');
assert.equal(player.onGround,true);assert.ok(player.pos.y>rock.maxY);
assert.ok(player.pos.x<rock.r,'mantle moves onto rock top, not into trunk collision');
p.reset();player.pos.x=1.5;player.pos.y=2.3;player.onGround=false;
player.vel.y=-1;
p.update(.016,true,-1,0);
assert.equal(p.mode,'WALL_RUN','airborne movement into wall starts bounded run');
assert.ok(player.vel.y>=1,'wall-run provides controlled upwards momentum');
const afterFirst=stats.sp;
p.update(.016,true,-1,0);
assert.ok(stats.sp<afterFirst,'running costs energy per second');
assert.ok(Math.hypot(player.vel.x,player.vel.z)>7,'wall run has stable tangential velocity');
assert.equal(p.jumpFromWall(),true,'wall jump responds to user jump input');
assert.equal(p.mode,'AIR');assert.ok(player.vel.x>0,'wall jump launches away from surface');
assert.equal(player._jumpCount,2,'wall jump does not grant infinite double jumps');
p.reset();
assert.equal(p.beginFlip(1,0),true);
assert.equal(p.flipType,'right');
p.animate(.25);assert.ok(Math.abs(player.rig.root.rotation.z)>2,'visual rotates while collider remains upright');
p.animate(.4);almost(player.rig.root.rotation.z,0);
assert.equal(p.flipT,-1,'rotation ends exactly neutral');
const startEnergy=stats.sp;stats.sp=0;
assert.equal(p.beginFlip(0,-1),false,'flip is gated by actual stamina');
stats.sp=startEnergy;
const collide=await import(asModule(await source('src/world/obstacles-p7.js')));
const grid=new collide.NatureObstaclesP7(12);
grid.register(0,0,1.05,0,5,'tree');
grid.register(3,0,.9,0,2,'rock');
let person={x:.2,z:0};
grid.collide(person,.43,1);
assert.ok(Math.hypot(person.x,person.z)>=1.48-.0001,'tree trunk cannot be walked through');
person={x:3.3,z:0};grid.collide(person,.43,1);
assert.ok(Math.hypot(person.x-3,person.z)>=1.33-.0001,'small rock cannot be walked through');
const ps=['src/main.js','src/player/player.js','src/world/scatter.js','src/systems/save.js','src/combat/combat.js'];
const texts=Object.fromEntries(await Promise.all(ps.map(async p=>[p,await source(p)])));
assert.ok(texts['src/main.js'].includes('this.p13Enabled'),'gated P13 release');
assert.ok(texts['src/player/player.js'].includes('new FuryTraversalP13(game,this)'),'traversal genuinely wired');
assert.ok(texts['src/player/player.js'].includes('landingRock(g'),'rock top collision actually used');
assert.ok(texts['src/player/player.js'].includes('this.fury.beginFlip(mx,mz)'),'directional acrobatic flip in jump');
assert.ok(texts['src/world/scatter.js'].includes('Math.min(2.55,s*Math.max(jx,jz)*.86)'),'rock collider more closely matches rendered scale');
assert.ok(texts['src/systems/save.js'].includes('highfly_p13_save'),'P812 never overwritten');
assert.ok(texts['src/combat/combat.js'].includes('touchAttackHold'),'hold attack combo preserved');
console.log('HIGHFLY P13 FURY: trees/rocks solid, ledge grab/mantle, wall run/jump, energy, acrobatic rotation, save isolation — PASS');
