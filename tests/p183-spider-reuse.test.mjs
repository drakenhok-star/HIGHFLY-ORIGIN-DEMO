import assert from 'node:assert/strict';
import {readFile,stat} from 'node:fs/promises';
import {ITEM_DB} from '../src/systems/inventory.js';
import {P183_PENDING_SPECIES,speciesReadyP183} from '../src/world/species-gate-p183.js';
const path=new URL('../assets/models/spider_quaternius_cc0.glb',import.meta.url);
assert.equal((await stat(path)).size,130436);
const glb=await readFile(path);
assert.equal(glb.toString('ascii',0,4),'glTF');assert.equal(glb.readUInt32LE(4),2);
assert.equal(glb.readUInt32LE(8),glb.length);
const len=glb.readUInt32LE(12),j=JSON.parse(glb.toString('utf8',20,20+len));
assert.equal(j.skins?.[0]?.joints?.length,39);
for(const s of ['Spider_Attack','Spider_Death','Spider_Idle','Spider_Walk','Spider_Jump'])assert.ok(j.animations.some(a=>a.name===s));
assert.ok(j.extensionsUsed.includes('EXT_meshopt_compression'));
assert.ok(speciesReadyP183(P183_PENDING_SPECIES.find(s=>s.id==='forest_spider'),['spider']));
assert.equal(ITEM_DB.spider_silk.type,'misc');assert.equal(ITEM_DB.spider_silk.damage,undefined);
const src=await readFile(new URL('../src/core/assets.js',import.meta.url),'utf8');
const en=await readFile(new URL('../src/entities/enemies.js',import.meta.url),'utf8');
assert.match(src,/setMeshoptDecoder\(MeshoptDecoder\)/);assert.match(en,/_spawnSpider\(/);
assert.match(en,/Spider_Attack/);assert.match(en,/spider_silk/);
console.log('P18.3 SPIDER CC0 verified: real meshopt GLB + 39 joints + 5 clips + integration');
