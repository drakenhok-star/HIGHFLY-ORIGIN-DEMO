import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {runInNewContext} from 'node:vm';
import {makeNoise2D,fbm} from '../src/core/noise.js';
import {P183B_CAMPS,resolveBiomeCampP183b,resolveCoastSitesP183b} from '../src/world/biome-families-p183b.js';
import {realForestP183c,banditTrailP183c,treeNoiseP183c} from '../src/world/habitat-p183c.js';
import {worldIsSafeP18} from '../src/world/world-registry-p18.js';
import {ECO_NAMES_P183C,ECO_COLORS_P183C,ecologyZoneP183c,ecologyCampsP183c} from '../src/ui/ecology-radar-p183c.js';
let src=await readFile(new URL('../src/world/terrain.js',import.meta.url),'utf8');
src=src.replace(/^import .*;\s*$/gm,'').replace('export class Terrain','class Terrain');
const ctx={makeNoise2D,fbm,Math};
runInNewContext(src+'\nthis.h=Terrain.prototype.getHeight;this.s=Terrain.prototype.getSlope;',ctx);
const t={waterY:-2,noise:makeNoise2D(1337)};
t.getHeight=function(x,z){return ctx.h.call(this,x,z);};
t.getSlope=function(x,z){return ctx.s.call(this,x,z);};
assert.ok(treeNoiseP183c(-190,505)>.2);
assert.ok(realForestP183c(t,-190,505),'goblins inside a real tree-eligible forest');
assert.ok(realForestP183c(t,-210,420),'spiders inside a real tree-eligible forest');
assert.ok(realForestP183c(t,-350,470),'forest wolves inside a real tree-eligible forest');
assert.ok(!realForestP183c(t,-332,64),'former goblin grassy field must be rejected');
assert.ok(!realForestP183c(t,-228,183),'former spider grassy field rejected');
assert.ok(banditTrailP183c(215,-112)>.9);
assert.equal(banditTrailP183c(0,40),0);
const allow=(x,z)=>!worldIsSafeP18(x,z)&&Math.abs(x)<1100&&Math.abs(z)<1100;
const found=P183B_CAMPS.map(c=>({c,site:resolveBiomeCampP183b(t,c,allow)}));
for(const {c,site} of found)assert.ok(site,'habitat not valid for '+c.id);
for(const {c,site} of found.filter(x=>x.c.biome==='forest'))assert.ok(realForestP183c(t,site.x,site.z));
const boars=found.filter(x=>x.c.type==='boar');
assert.deepEqual(boars.map(x=>[x.c.x,x.c.z]),[[207,153],[272,65]],'working boars do not move');
const orc=found.find(x=>x.c.type==='orc');
assert.ok(Math.hypot(orc.site.x+220,orc.site.z+180)>100,'orc far from draugr ruins');
const coast=resolveCoastSitesP183b(t,allow);
assert.ok(coast.length>0);
assert.equal(ECO_NAMES_P183C.goblin,'Goblin');
assert.ok(ECO_COLORS_P183C.crab);
assert.equal(ecologyZoneP183c({terrain:t},{x:-190,z:505}),'Bosque de Pinos');
assert.equal(ecologyZoneP183c({terrain:t},{x:0,z:40}),'Aldea segura');
assert.equal(ecologyZoneP183c({terrain:t},{x:215,z:-112}),'Sendero de bandidos');
const animals=[{alive:true,group:{position:{x:-190,z:505}},p183bSpec:{id:'bosque_goblins'},type:'goblin',speciesId:'goblin'}];
const fake={enemies:{list:animals,p183bSites:[{spec:{id:'bosque_goblins',type:'goblin',biome:'forest'},site:{x:-190,z:505}}]}};
assert.equal(ecologyCampsP183c(fake)[0].alive,1);
const files=['src/entities/enemies.js','src/ui/world-map-p34.js','src/ui/biome-tour-p183c.js','src/world/scatter.js','src/core/assets.js'];
for(const file of files){const s=await readFile(new URL('../'+file,import.meta.url),'utf8');
 if(file.includes('enemies.js'))assert.match(s,/highflyP183cReport/);
 if(file.includes('world-map'))assert.match(s,/ecologyRadarSummaryP183c/);
 if(file.includes('biome-tour'))assert.match(s,/safeTeleport/);
}
console.log('P18.3c PASS: 10 real habitat camps, working boars stable, forest valid, orc separated, coast found, live radar');
