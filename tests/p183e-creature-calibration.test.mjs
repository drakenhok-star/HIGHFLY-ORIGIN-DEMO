import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {P183B_CAMPS} from '../src/world/biome-families-p183b.js';
const get=async p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const enemy=await get('src/entities/enemies.js'),player=await get('src/player/player.js');
const assets=await get('src/core/assets.js'),radar=await get('src/ui/ecology-radar-p183c.js');
const main=await get('src/main.js');
const yeti=P183B_CAMPS.find(c=>c.type==='yeti');
assert.equal(yeti.model,'yeti_highland','humanlike alternate CC0 yeti');
assert.equal(yeti.clips.attack,'Punch','alt yeti has Punch, not original Bite_Front');
assert.match(assets,/yeti_highland: \{ targetHeight: 3.3, animatedBounds: true \}/);
assert.match(assets,/crab: \{ targetHeight: 1.35, animatedBounds: true \}/);
assert.match(assets,/orc: \{ targetHeight: 3.15, animatedBounds: true \}/);
assert.match(enemy,/prairie_wolf:'Lobo común'/);
assert.doesNotMatch(enemy,/Lobo común \(ClaudeCraft\)/);
assert.match(enemy,/scale\.multiplyScalar\(2.5\)/,'elite 4m vs player 1.9');
assert.match(enemy,/scale\.multiplyScalar\(2.7\)/,'glacial alpha > common');
assert.match(enemy,/e\.attackRange=Math\.max\(e\.attackRange,3.8\)/);
assert.match(player,/E Recoger botín/);
assert.match(player,/E Abrir cofre/);
assert.doesNotMatch(player,/拾取战利品|打开宝箱/);
assert.ok(main.includes('p183eEnabled'));
assert.ok(radar.includes('Lobo alfa glacial'));
const bin=await readFile(new URL('../assets/models/yetialt_quaternius_cc0.glb',import.meta.url));
assert.equal(bin.toString('ascii',0,4),'glTF');
assert.equal(bin.readUInt32LE(4),2);
assert.equal(bin.readUInt32LE(8),bin.length);
assert.equal(bin.length,149784);
const length=bin.readUInt32LE(12),j=JSON.parse(bin.toString('utf8',20,20+length));
assert.equal(j.skins[0].joints.length,43);
for(const name of ['Idle','Walk','Run','Punch','Death'])assert.ok(j.animations.some(a=>a.name===name),name);
assert.ok(j.extensionsRequired.includes('EXT_meshopt_compression'));
console.log('P183e PASS: two alpha scales, realistic 43-bone Quaternius Yeti, crab, orc, names and Spanish E');
